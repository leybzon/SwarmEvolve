#!/usr/bin/env python3
"""Check which Claude models the experiment key can use, without spending.

Calls only the Models API (``GET /v1/models/{id}``), which is not billed.
Reads the key from ``SWARMEVOLVE_ANTHROPIC_API_KEY`` (environment, or the
git-ignored ``.env`` at the repo root). The key is never printed, logged
or written; error messages are redacted before they are stored. A key that
is not scoped to a workspace needs a workspace ID, sent as the
``anthropic-workspace-id`` header: ``SWARMEVOLVE_ANTHROPIC_WORKSPACE_ID``,
else ``ANTHROPIC_WORKSPACE_ID``.

Writes ``<out-dir>/model_access.json`` and renders ``<out-dir>/MODEL_ACCESS.md``.

Exit codes: 0 checked (whatever the per-model result), 1 key missing,
2 the key was rejected (401).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
KEY_VAR = "SWARMEVOLVE_ANTHROPIC_API_KEY"
WORKSPACE_VARS = ("SWARMEVOLVE_ANTHROPIC_WORKSPACE_ID", "ANTHROPIC_WORKSPACE_ID")
DEFAULT_MODELS = ["claude-sonnet-5-5", "claude-haiku-5-5", "claude-opus-5-5"]


def _setting(name: str) -> str | None:
    """Value from the environment, else from the repo's .env."""
    value = os.environ.get(name, "").strip()
    if value:
        return value
    env_file = REPO_ROOT / ".env"
    if env_file.is_file():
        from dotenv import dotenv_values

        return (dotenv_values(env_file).get(name) or "").strip() or None
    return None


def _load_key() -> str | None:
    return _setting(KEY_VAR)


def _load_workspace() -> tuple[str | None, str | None]:
    """(workspace id, the variable it came from)."""
    for name in WORKSPACE_VARS:
        value = _setting(name)
        if value:
            return value, name
    return None, None


def _redact(text: str, key: str) -> str:
    text = text.replace(key, "<redacted>")
    return re.sub(r"sk-ant-[A-Za-z0-9_\-]+", "<redacted>", text)


def check(models: list[str], key: str, workspace_id: str | None = None) -> list[dict]:
    import anthropic

    headers = {"anthropic-workspace-id": workspace_id} if workspace_id else None
    client = anthropic.Anthropic(api_key=key, max_retries=2, default_headers=headers)
    rows = []
    for model_id in models:
        row: dict = {"model": model_id}
        try:
            m = client.models.retrieve(model_id)
            row.update(status="available", display_name=m.display_name)
        except anthropic.NotFoundError:
            row["status"] = "not_found"
        except anthropic.PermissionDeniedError as e:
            row.update(status="permission_denied", detail=_redact(str(e.message), key))
        except anthropic.AuthenticationError as e:
            row.update(status="auth_failed", detail=_redact(str(e.message), key))
        except anthropic.APIStatusError as e:
            row.update(status=f"http_{e.status_code}", detail=_redact(str(e.message), key))
        except anthropic.APIConnectionError as e:
            row.update(status="connection_error", detail=_redact(str(e), key))
        rows.append(row)
    return rows


def render(data: dict, source: str) -> str:
    lines = [
        "# Model access",
        "",
        f"Generated by `scripts/check_model_access.py` from `{source}` "
        f"(checked {data['checked_utc']}). Uses only `GET /v1/models/{{id}}` "
        f"(not billed) with `{KEY_VAR}`; workspace header from "
        f"`{data.get('workspace_variable') or 'none'}`.",
        "",
        "| Model | Result | Display name |",
        "|---|---|---|",
    ]
    for row in data["models"]:
        lines.append(f"| `{row['model']}` | {row['status']} | {row.get('display_name', '')} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out-dir", type=Path, default=REPO_ROOT / "reports" / "setup")
    p.add_argument("--models", nargs="+", default=DEFAULT_MODELS)
    args = p.parse_args(argv)
    key = _load_key()
    if not key:
        print(f"{KEY_VAR} is not set (environment or .env)", file=sys.stderr)
        return 1
    workspace_id, workspace_var = _load_workspace()
    rows = check(args.models, key, workspace_id)
    data = {
        "checked_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "key_variable": KEY_VAR,
        "workspace_variable": workspace_var,
        "models": rows,
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    data_path = args.out_dir / "model_access.json"
    data_path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    (args.out_dir / "MODEL_ACCESS.md").write_text(render(data, data_path.name))
    for row in rows:
        print(f"{row['model']}: {row['status']}")
    return 2 if all(r["status"] == "auth_failed" for r in rows) else 0


if __name__ == "__main__":
    sys.exit(main())
