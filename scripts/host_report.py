#!/usr/bin/env python3
"""Record the host: OS, kernel, CPU, cores, RAM, free disk, toolchain.

Writes ``<out-dir>/host.json`` and renders ``<out-dir>/HOST.md`` from it.

    python scripts/host_report.py --out-dir reports/setup
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

TOOLS = {
    "git": ["git", "--version"],
    "python3.11": ["python3.11", "--version"],
    "clang++": ["clang++", "--version"],
    "g++": ["g++", "--version"],
    "make": ["make", "--version"],
    "jq": ["jq", "--version"],
    "tmux": ["tmux", "-V"],
    "docker": ["docker", "--version"],
}


def _first_line(cmd: list[str]) -> str | None:
    if shutil.which(cmd[0]) is None:
        return None
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    out = (proc.stdout or proc.stderr).strip().splitlines()
    return out[0] if out else None


def _os_release() -> str:
    try:
        for line in Path("/etc/os-release").read_text().splitlines():
            if line.startswith("PRETTY_NAME="):
                return line.split("=", 1)[1].strip('"')
    except OSError:
        pass
    return platform.platform()


def _lscpu() -> dict[str, str]:
    proc = subprocess.run(["lscpu"], capture_output=True, text=True, check=False)
    fields: dict[str, str] = {}
    for line in proc.stdout.splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip()
    return fields


def _mem_total_bytes() -> int:
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemTotal:"):
            return int(line.split()[1]) * 1024
    raise RuntimeError("MemTotal not found in /proc/meminfo")


def collect() -> dict:
    cpu = _lscpu()
    sockets = int(cpu.get("Socket(s)", "1"))
    cores_per_socket = int(cpu.get("Core(s) per socket", "0"))
    disk = shutil.disk_usage(REPO_ROOT)
    return {
        "recorded_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "hostname": platform.node(),
        "os": _os_release(),
        "kernel": platform.release(),
        "arch": platform.machine(),
        "cpu_model": cpu.get("Model name", "unknown"),
        "physical_cores": sockets * cores_per_socket,
        "logical_cpus": os.cpu_count(),
        "threads_per_core": int(cpu.get("Thread(s) per core", "1")),
        "ram_total_bytes": _mem_total_bytes(),
        "disk_path": str(REPO_ROOT),
        "disk_total_bytes": disk.total,
        "disk_free_bytes": disk.free,
        "toolchain": {name: _first_line(cmd) for name, cmd in TOOLS.items()},
        "platform_label": "dev",
    }


def _gib(n: int) -> str:
    return f"{n / 2**30:.1f} GiB"


def render(info: dict, source: str) -> str:
    rows = [
        ("OS", info["os"]),
        ("Kernel", info["kernel"]),
        ("Architecture", info["arch"]),
        ("CPU model", info["cpu_model"]),
        (
            "Cores",
            f"{info['physical_cores']} physical, {info['logical_cpus']} logical "
            f"({info['threads_per_core']} threads/core)",
        ),
        ("RAM", _gib(info["ram_total_bytes"])),
        (
            "Free disk",
            f"{_gib(info['disk_free_bytes'])} of {_gib(info['disk_total_bytes'])} "
            f"(at `{info['disk_path']}`)",
        ),
    ]
    lines = [
        "# Host",
        "",
        f"Generated by `scripts/host_report.py` from `{source}` "
        f"(recorded {info['recorded_utc']}). Platform label: **{info['platform_label']}** "
        "(host-side records are never the canonical platform, which is the eval container "
        "described in `prereg/PLATFORM.json`).",
        "",
        "| Item | Value |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in rows],
        "",
        "## Toolchain",
        "",
        "| Tool | Version |",
        "|---|---|",
        *[f"| {k} | {v or 'not installed'} |" for k, v in info["toolchain"].items()],
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out-dir", type=Path, default=REPO_ROOT / "reports" / "setup")
    args = p.parse_args(argv)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    data_path = args.out_dir / "host.json"
    data_path.write_text(json.dumps(collect(), indent=2, sort_keys=True) + "\n")
    info = json.loads(data_path.read_text())
    (args.out_dir / "HOST.md").write_text(render(info, data_path.name))
    print(f"wrote {data_path} and {args.out_dir / 'HOST.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
