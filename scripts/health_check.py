#!/usr/bin/env python3
"""Setup health checks: side neutrality and match throughput.

Runs on the host with the human-written baselines only (no LLM code).

* Side neutrality: ``pursuit_v1`` vs itself and ``cluster_v1`` vs itself,
  ``--n-matches`` seeds each from ``--seed-base``. A side-neutral engine
  gives a mean Team-A score whose 95% CI includes 0.
* Throughput: matches per second for ``--n-matches`` pursuit-vs-cluster
  matches across ``--workers`` processes (default: all logical CPUs).
  Wall time includes the one-time compile in each worker.

Results (with every per-match row) go to ``<out-dir>/health_results.json``
and ``<out-dir>/HEALTH.md`` is rendered from that file. ``--render-only``
re-renders the Markdown without running anything.

    python scripts/health_check.py --out-dir reports/setup
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "scripts"))

import compile_flags  # noqa: E402
import fitness  # noqa: E402

BASELINES = REPO_ROOT / "src" / "baselines"
NEUTRALITY_PAIRS = [("pursuit_v1", "pursuit_v1"), ("cluster_v1", "cluster_v1")]
THROUGHPUT_PAIR = ("pursuit_v1", "cluster_v1")


def _git_sha() -> str:
    return subprocess.run(
        ["git", "-C", str(REPO_ROOT), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def _write_status(path: Path, **fields) -> None:
    fields["updated_utc"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    path.write_text(json.dumps(fields, sort_keys=True) + "\n")


def _evaluate(a: str, b: str, *, n: int, seed_base: int, workers: int, scratch: Path) -> dict:
    result = fitness.evaluate_fitness(
        BASELINES / f"{a}.cpp",
        BASELINES / f"{b}.cpp",
        n_matches=n,
        seed_base=seed_base,
        workers=workers,
        scratch_root=scratch,
        backend="host",  # a host check by design; fitness now defaults to the sandbox
    )
    return result.to_dict()


def run(args: argparse.Namespace) -> dict:
    status = args.out_dir / "health_status.json"
    scratch = Path(tempfile.mkdtemp(prefix="health_"))
    compiler = fitness._find_compiler()
    if compiler is None:
        raise RuntimeError("no C++ compiler found")
    results: dict = {
        "started_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "git_sha": _git_sha(),
        "platform_label": "dev",
        "compiler": compiler,
        "compiler_family": compile_flags.compiler_family(compiler),
        "compile_flags": compile_flags.engine_flags(compiler),
        "workers": args.workers,
        "n_matches": args.n_matches,
        "neutrality": [],
    }
    for a, b in NEUTRALITY_PAIRS:
        _write_status(status, state="running", step=f"neutrality {a} vs {b}")
        r = _evaluate(
            a, b, n=args.n_matches, seed_base=args.seed_base, workers=args.workers, scratch=scratch
        )
        results["neutrality"].append({"team_a": a, "team_b": b, "result": r})
    a, b = THROUGHPUT_PAIR
    _write_status(status, state="running", step=f"throughput {a} vs {b}")
    t0 = time.monotonic()
    r = _evaluate(
        a,
        b,
        n=args.n_matches,
        seed_base=args.throughput_seed_base,
        workers=args.workers,
        scratch=scratch,
    )
    wall = time.monotonic() - t0
    results["throughput"] = {
        "team_a": a,
        "team_b": b,
        "wall_seconds_measured": wall,
        "result": r,
    }
    results["finished_utc"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    _write_status(status, state="done")
    return results


def render(results: dict, source: str) -> str:
    lines = [
        "# Setup health checks",
        "",
        f"Generated by `scripts/health_check.py` from `{source}`. Platform label: "
        f"**{results['platform_label']}** (not the canonical platform). Commit "
        f"`{results['git_sha'][:12]}`, compiler `{results['compiler']}` "
        f"({results['compiler_family']}), {results['workers']} workers, "
        f"started {results['started_utc']}.",
        "",
        "## Side neutrality",
        "",
        "Self-play, Team-A perspective (+1 A win, -1 B win, 0 draw). 95% CI is the "
        "percentile bootstrap from `fitness.evaluate_fitness`. Pass: the CI includes 0.",
        "",
        "| Pairing | Seeds | A wins | B wins | Draws | Invalid | Mean | 95% CI | Pass |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    all_pass = True
    for entry in results["neutrality"]:
        r = entry["result"]
        ok = r["ci_low"] <= 0.0 <= r["ci_high"] and r["invalid"] == 0
        all_pass &= ok
        last_seed = r["seed_base"] + r["n_matches"] - 1
        lines.append(
            f"| {entry['team_a']} vs {entry['team_b']} | {r['seed_base']}-{last_seed} "
            f"| {r['wins_a']} | {r['wins_b']} | {r['draws']} | {r['invalid']} "
            f"| {r['mean']:+.4f} | [{r['ci_low']:+.4f}, {r['ci_high']:+.4f}] "
            f"| {'yes' if ok else '**no**'} |"
        )
    t = results["throughput"]
    r = t["result"]
    engine_seconds = sum(m["wall_ms"] for m in r["per_match"]) / 1000
    lines += [
        "",
        f"Side neutrality overall: **{'pass' if all_pass else 'FAIL'}**.",
        "",
        "## Throughput",
        "",
        f"{r['n_matches']} matches of {t['team_a']} vs {t['team_b']} (seeds "
        f"{r['seed_base']}-{r['seed_base'] + r['n_matches'] - 1}) on {r['workers']} workers.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Wall time, including one compile per worker | {t['wall_seconds_measured']:.2f} s |",
        f"| Matches per second (wall) | {r['n_matches'] / t['wall_seconds_measured']:.1f} |",
        f"| Mean engine time per match (single process) | "
        f"{1000 * engine_seconds / r['n_matches']:.1f} ms |",
        f"| Invalid matches | {r['invalid']} |",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out-dir", type=Path, default=REPO_ROOT / "reports" / "setup")
    p.add_argument("--n-matches", type=int, default=4000)
    p.add_argument("--seed-base", type=int, default=100000)
    p.add_argument("--throughput-seed-base", type=int, default=200000)
    p.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    p.add_argument("--render-only", action="store_true")
    args = p.parse_args(argv)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    data_path = args.out_dir / "health_results.json"
    if not args.render_only:
        if data_path.exists():
            p.error(f"{data_path} exists; results are append-only, pick another --out-dir")
        data_path.write_text(json.dumps(run(args), indent=2, sort_keys=True) + "\n")
    results = json.loads(data_path.read_text())
    (args.out_dir / "HEALTH.md").write_text(render(results, data_path.name))
    print(f"wrote {args.out_dir / 'HEALTH.md'} from {data_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
